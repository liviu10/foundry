    /** @param  list<array{0: string, 1: string}>  $crumbs */
    private function breadcrumbLd(array $crumbs): array
    {
        $items = [];
        foreach ($crumbs as $i => [$name, $path]) {
            $items[] = ['@type' => 'ListItem', 'position' => $i + 1, 'name' => $name, 'item' => $this->url($path)];
        }

        return ['@context' => 'https://schema.org', '@type' => 'BreadcrumbList', 'itemListElement' => $items];
    }

    /** @param  array<string, mixed>|null  $about */
    private function articleLd(string $headline, string $description, string $path, ?string $modified, ?array $about = null): array
    {
        $ld = [
            '@context' => 'https://schema.org',
            '@type' => 'TechArticle',
            'headline' => Support::excerpt($headline, 110),
            'description' => $description,
            'url' => $this->url($path),
            'mainEntityOfPage' => $this->url($path),
            'inLanguage' => $this->config['language'],
            'image' => $this->url($this->asset('img/og-image.png')),
            'isPartOf' => ['@type' => 'WebSite', 'name' => $this->config['name'], 'url' => $this->url('/')],
            'proficiencyLevel' => 'Expert',
        ];
        if ($modified !== null) {
            $ld['dateModified'] = $modified;
        }
        if ($about !== null) {
            $ld['about'] = $about;
        }

        return $ld;
    }

    private function report(float $start): void
    {
        $unresolved = array_unique($this->linker->unresolved);
        printf("Built %d pages, %d classes, %d methods/functions, %d search entries in %.1fs\n",
            $this->pages, $this->classCount(), $this->lib->methodCount(), count($this->search), microtime(true) - $start);
        printf("Download: %s (%d files, %s, sha256 %s)\n", $this->download['name'], $this->download['count'], Support::humanBytes($this->download['size']), $this->download['sha256']);
        printf("Output: %s\n", $this->outDir());
        foreach ($this->lib->warnings as $w) {
            echo "WARNING: {$w}\n";
        }
        foreach ($unresolved as $ref) {
            echo "WARNING: guide references unknown method {$ref}\n";
        }
    }
