    private function pageHome(): void
    {
        $content = $this->render('home');
        $this->emit('/', [
            'title' => 'Foundry — Standalone, zero-dependency PHP utility classes',
            'description' => Support::excerpt("Foundry is a suite of {$this->classCount()} standalone, single-file PHP 8.3+ utility classes with zero dependencies: validation, CSV/XLSX import, databases, HTTP, security and more. Every error throws an explicit exception.", 160),
            'lastmod' => $this->latestModified(),
            'layout' => 'home',
            'jsonld' => [
                [
                    '@context' => 'https://schema.org',
                    '@type' => 'WebSite',
                    'name' => $this->config['name'],
                    'url' => $this->url('/'),
                    'inLanguage' => $this->config['language'],
                    'description' => $this->config['tagline'],
                ],
                [
                    '@context' => 'https://schema.org',
                    '@type' => 'SoftwareSourceCode',
                    'name' => 'Foundry PHP utility library',
                    'description' => "{$this->classCount()} standalone, single-file PHP utility classes with zero third-party dependencies and explicit exceptions instead of silent failures.",
                    'url' => $this->url('/'),
                    'programmingLanguage' => ['@type' => 'ComputerLanguage', 'name' => 'PHP'],
                    'runtimePlatform' => 'PHP 8.3+, PHP 7.4',
                    'codeSampleType' => 'full solution',
                    'license' => $this->config['license'],
                    'downloadUrl' => $this->url($this->download['url']),
                ],
            ],
        ], $content);
    }

    private function pageDocsIndex(): void
    {
        $content = $this->render('docs-index');
        $toc = [['id' => 'getting-started', 'text' => 'Getting started', 'level' => 2]];
        foreach ($this->lib->categories as $cat) {
            $toc[] = ['id' => $cat['slug'], 'text' => $cat['name'], 'level' => 2];
        }
        $this->emit('/docs/', [
            'title' => 'Documentation — Foundry PHP utility classes',
            'description' => Support::excerpt("Reference documentation for all {$this->classCount()} Foundry classes: installation, design principles, guides and a complete method reference with parameters, return types and exceptions.", 160),
            'toc' => $toc,
            'lastmod' => $this->latestModified(),
            'breadcrumbs' => [['Home', '/'], ['Documentation', '/docs/']],
            'jsonld' => [$this->breadcrumbLd([['Home', '/'], ['Documentation', '/docs/']])],
        ], $content);
        $this->search[] = ['t' => 'Documentation', 'u' => '/docs/', 's' => 'Overview', 'd' => 'All classes by category.', 'k' => 'guide'];
    }

    /** @param  array<string, mixed>  $guide */
    private function pageGuide(array $guide): void
    {
        $md = new Markdown($this->linker, $this->renderer);
        $html = $md->render($guide['body']);
        $path = '/docs/'.$guide['slug'].'/';
        $crumbs = [['Home', '/'], ['Documentation', '/docs/'], [$guide['title'], $path]];

        $this->emit($path, [
            'title' => $guide['title'].' — Foundry PHP utilities',
            'description' => $guide['description'],
            'toc' => $md->headings,
            'breadcrumbs' => $crumbs,
            'markdown' => '/docs/'.$guide['slug'].'.md',
            'type' => 'article',
            'lastmod' => $guide['lastmod'],
            'jsonld' => [$this->articleLd($guide['title'], $guide['description'], $path, $guide['lastmod']), $this->breadcrumbLd($crumbs)],
        ], $this->render('guide', ['guide' => $guide, 'body' => $html]));

        $mdText = "# {$guide['title']}\n\n> {$guide['description']}\n\nCanonical: ".$this->url($path)."\n\n".$this->absoluteLinks($guide['body'])."\n";
        $this->writeMarkdown('/docs/'.$guide['slug'].'.md', $guide['title'], $mdText);

        $this->search[] = ['t' => $guide['title'], 'u' => $path, 's' => $guide['group'], 'd' => $guide['description'], 'k' => 'guide'];
        foreach ($md->headings as $h) {
            $this->search[] = ['t' => $h['text'], 'u' => $path.'#'.$h['id'], 's' => $guide['title'], 'd' => '', 'k' => 'section'];
        }
    }

    /** @param  array<string, mixed>  $class */
    private function pageClass(array $class): void
    {
        $path = $this->classPath($class);
        $body = $this->renderer->classBody($class);
        $catUrl = '/docs/#'.$class['category']['slug'];
        $crumbs = [['Home', '/'], ['Documentation', '/docs/'], [$class['category']['name'], $catUrl], [$class['name'], $path]];
        $description = Support::excerpt("PHP {$class['name']} class: ".Support::plain($class['overview']).' Standalone, single-file, zero dependencies.', 160);

        $this->emit($path, [
            'title' => $this->classTitle($class),
            'description' => $description,
            'toc' => $body['toc'],
            'breadcrumbs' => $crumbs,
            'markdown' => '/docs/'.$class['slug'].'.md',
            'type' => 'article',
            'lastmod' => $class['lastmod'],
            'jsonld' => [
                $this->articleLd($class['name'].' — PHP utility class reference', $description, $path, $class['lastmod'], [
                    '@type' => 'SoftwareSourceCode',
                    'name' => $class['fqcn'],
                    'programmingLanguage' => 'PHP',
                    'runtimePlatform' => $class['since'].'+',
                    'version' => $class['version'],
                ]),
                $this->breadcrumbLd($crumbs),
            ],
        ], $this->render('class', ['class' => $class, 'body' => $body['html']]));

        $this->writeMarkdown('/docs/'.$class['slug'].'.md', $class['name'], $this->renderer->classMarkdown($class, $this->url($path)));

        $this->search[] = ['t' => $class['name'], 'u' => $path, 's' => $class['category']['name'], 'd' => Support::excerpt(Support::plain($class['overview']), 120), 'k' => 'class'];
        foreach ($class['methods'] as $m) {
            $title = $m['kind'] === 'constructor' ? 'new '.$class['name'].'()' : $class['name'].($m['kind'] === 'static' ? '::' : '->').$m['name'].'()';
            $this->search[] = ['t' => $title, 'u' => $path.'#'.$m['id'], 's' => $class['name'], 'd' => Support::excerpt($m['summary'], 110), 'k' => 'method'];
        }
        foreach ($class['functions'] as $f) {
            $this->search[] = ['t' => $f['name'].'()', 'u' => $path.'#'.$f['id'], 's' => $class['name'], 'd' => Support::excerpt($f['summary'], 110), 'k' => 'function'];
        }
    }

    private function page404(): void
    {
        $this->emit('/404.html', [
            'title' => 'Page not found — Foundry',
            'description' => 'The page you are looking for does not exist.',
            'robots' => 'noindex, follow',
            'layout' => 'home',
        ], $this->render('404'));
    }

    /**
     * @param  array<string, mixed>  $page
     */
    private function emit(string $path, array $page, string $content): void
    {
        $page += [
            'path' => $path,
            'layout' => 'docs',
            'type' => 'website',
            'toc' => [],
            'breadcrumbs' => [],
            'markdown' => null,
            'jsonld' => [],
            'robots' => 'index, follow, max-snippet:-1, max-image-preview:large',
            'lastmod' => null,
        ];
        if (mb_strlen($page['title']) > 65) {
            $this->lib->warnings[] = "Long title ({$path}): {$page['title']}";
        }
        $page['canonical'] = $this->url($path === '/404.html' ? '/' : $path);
        [$page['prev'], $page['next']] = $this->neighbours($path);

        $html = $this->render('layout', ['page' => $page, 'content' => $content]);
        $file = $this->outDir().($path === '/404.html' ? '/404.html' : $path.'index.html');
        Support::write($file, $html);
        $this->pages++;

        if (str_starts_with($page['robots'], 'index')) {
            $this->sitemap[] = ['loc' => $this->url($path), 'lastmod' => substr((string) ($page['lastmod'] ?? date('c')), 0, 10)];
        }
    }

    /** @return array{0: array{title: string, url: string}|null, 1: array{title: string, url: string}|null} */
    private function neighbours(string $path): array
    {
        $flat = array_merge(...array_map(static fn (array $g): array => $g['items'], $this->nav));
        foreach ($flat as $i => $item) {
            if ($item['url'] === $path) {
                return [$flat[$i - 1] ?? null, $flat[$i + 1] ?? null];
            }
        }

        return [null, null];
    }

    private function latestModified(): string
    {
        $dates = array_merge(array_column($this->lib->classes, 'lastmod'), array_column($this->guides, 'lastmod'));
        usort($dates, static fn (string $a, string $b): int => strtotime($b) <=> strtotime($a));

        return $dates[0] ?? date('c');
    }

    // ------------------------------------------------------------------ content

    private function loadGuides(): void
    {
        $placeholders = [
            '{{class_count}}' => (string) $this->classCount(),
            '{{method_count}}' => (string) $this->lib->methodCount(),
            '{{download_url}}' => $this->download['url'],
            '{{download_name}}' => $this->download['name'],
            '{{download_size}}' => Support::humanBytes($this->download['size']),
            '{{download_sha256}}' => $this->download['sha256'],
            '{{extensions_table}}' => $this->extensionsTable(),
        ];

        foreach ($this->config['guides'] as $group => $slugs) {
            foreach ($slugs as $slug) {
                $file = $this->config['content_dir']."/guides/{$slug}.md";
                if (! is_file($file)) {
                    throw new RuntimeException("Guide not found: content/guides/{$slug}.md");
                }
                $raw = str_replace("\r\n", "\n", (string) file_get_contents($file));
                if (! preg_match('/^---\n(.*?)\n---\n(.*)$/s', $raw, $m)) {
                    throw new RuntimeException("Guide {$slug}.md has no front matter.");
                }
                $meta = [];
                foreach (explode("\n", $m[1]) as $line) {
                    if (preg_match('/^(\w+):\s*(.+)$/', $line, $kv)) {
                        $meta[$kv[1]] = trim($kv[2], " \"'");
                    }
                }
                foreach (['title', 'description'] as $required) {
                    if (empty($meta[$required])) {
                        throw new RuntimeException("Guide {$slug}.md: front matter '{$required}' is missing.");
                    }
                }
                $body = strtr(trim($m[2]), $placeholders);
                if (preg_match_all('/\{\{\w+\}\}/', $body, $left)) {
                    $this->lib->warnings[] = "Unknown placeholders in {$slug}.md: ".implode(', ', array_unique($left[0]));
                }
                $this->guides[$slug] = [
                    'slug' => $slug,
                    'group' => $group,
                    'title' => $meta['title'],
                    'nav' => $meta['nav'] ?? $meta['title'],
                    'description' => $meta['description'],
                    'body' => $body,
                    'lastmod' => Support::lastModified($file),
                ];
            }
        }
    }

    private function extensionsTable(): string
    {
        $byExt = [];
        foreach ($this->lib->classes as $c) {
            foreach ($c['extensions'] as $ext) {
                $byExt[$ext][] = $c['name'];
            }
        }
        uksort($byExt, static fn (string $a, string $b): int => [count($byExt[$b]), $a] <=> [count($byExt[$a]), $b]);
        $rows = ["| Extension | Required by |", '| --- | --- |'];
        foreach ($byExt as $ext => $classes) {
            $rows[] = "| `{$ext}` | ".implode(', ', array_map(static fn (string $c): string => "`{$c}`", $classes)).' |';
        }

        return implode("\n", $rows);
    }

    private function buildNav(): void
    {
        foreach ($this->config['guides'] as $group => $slugs) {
            $items = $group === array_key_first($this->config['guides']) ? [['title' => 'Introduction', 'url' => '/docs/']] : [];
            foreach ($slugs as $slug) {
                $items[] = ['title' => $this->guides[$slug]['nav'], 'url' => '/docs/'.$slug.'/'];
            }
            $this->nav[] = ['title' => $group, 'items' => $items];
        }
        foreach ($this->lib->categories as $cat) {
            $this->nav[] = [
                'title' => $cat['name'],
                'items' => array_map(fn (string $n): array => ['title' => $n, 'url' => $this->classPath($this->lib->classes[$n])], $cat['classes']),
            ];
        }
    }

    // ------------------------------------------------------------------ files

    private function outDir(): string
    {
        return rtrim(str_replace('\\', '/', (string) $this->config['output_dir']), '/');
    }

    private function copyAssets(): void
    {
        $src = rtrim((string) $this->config['assets_dir'], '/\\');
        $items = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($src, \FilesystemIterator::SKIP_DOTS));
        foreach ($items as $file) {
            $rel = str_replace('\\', '/', substr($file->getPathname(), strlen($src) + 1));
            $data = (string) file_get_contents($file->getPathname());
            $this->assetVersions[$rel] = substr(hash('sha256', $data), 0, 10);
            Support::write($this->outDir().'/assets/'.$rel, $data);
        }
        // Files browsers and crawlers request at the root.
        foreach (['img/favicon.ico' => 'favicon.ico', 'img/favicon.svg' => 'favicon.svg', 'img/apple-touch-icon.png' => 'apple-touch-icon.png'] as $from => $to) {
            if (is_file($src.'/'.$from)) {
                copy($src.'/'.$from, $this->outDir().'/'.$to);
            }
        }
    }

    /** Deterministic archive: sorted entries, fixed timestamps, so unchanged sources give the same SHA-256. */
    private function buildDownload(): void
    {
        $name = $this->config['download']['file'];
        $folder = $this->config['download']['folder'];
        $target = $this->outDir().'/downloads/'.$name;
        Support::write($target, '');
        unlink($target);

        $zip = new ZipArchive;
        if ($zip->open($target, ZipArchive::CREATE | ZipArchive::OVERWRITE) !== true) {
            throw new RuntimeException("Cannot create {$target}.");
        }
        $mtime = 0;
        foreach ($this->lib->classes as $c) {
            $mtime = max($mtime, (int) strtotime($c['lastmod']));
        }
        $names = array_column($this->lib->classes, 'path', 'file');
        ksort($names);
        foreach ($names as $file => $path) {
            $entry = "{$folder}/{$file}";
            $zip->addFromString($entry, str_replace("\r\n", "\n", (string) file_get_contents($path)));
            $zip->setMtimeName($entry, $mtime);
            $zip->setCompressionName($entry, ZipArchive::CM_DEFLATE, 9);
        }
        $zip->close();

        $this->download = [
            'name' => $name,
            'url' => '/downloads/'.$name,
            'size' => (int) filesize($target),
            'sha256' => hash_file('sha256', $target),
            'count' => count($names),
        ];
    }

    private function writeMarkdown(string $path, string $title, string $markdown): void
    {
        Support::write($this->outDir().$path, $markdown);
        $this->markdownDocs[] = ['title' => $title, 'url' => $this->url($path), 'md' => $markdown];
    }

    private function absoluteLinks(string $markdown): string
    {
        return (string) preg_replace('/\]\(\//', ']('.$this->config['base_url'].'/', $markdown);
    }

    private function writeSearchIndex(): void
    {
        $data = array_map(static fn (array $e): array => $e + ['d' => ''], $this->search);
        Support::write($this->outDir().'/search-index.json', json_encode($data, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR));
    }

    private function writeSitemap(): void
    {
        $xml = '<?xml version="1.0" encoding="UTF-8"?>'."\n".'<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'."\n";
        foreach ($this->sitemap as $u) {
            $xml .= '  <url><loc>'.Support::e($u['loc']).'</loc><lastmod>'.$u['lastmod'].'</lastmod></url>'."\n";
        }
        Support::write($this->outDir().'/sitemap.xml', $xml.'</urlset>'."\n");
    }

    private function writeRobots(): void
    {
        $bots = ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-SearchBot', 'Claude-User', 'PerplexityBot',
            'Perplexity-User', 'Google-Extended', 'Applebot-Extended', 'Amazonbot', 'meta-externalagent', 'CCBot', 'DuckAssistBot', 'MistralAI-User'];
        $txt = "# Foundry documentation. Search engines and AI assistants are welcome.\n"
            ."# Machine-readable docs: /llms.txt, /llms-full.txt and a .md version of every page.\n\n"
            ."User-agent: *\nAllow: /\nDisallow: /downloads/\n\n";
        foreach ($bots as $bot) {
            $txt .= "User-agent: {$bot}\n";
        }
        $txt .= "Allow: /\nDisallow: /downloads/\n\nSitemap: ".$this->url('/sitemap.xml')."\n";
        Support::write($this->outDir().'/robots.txt', $txt);
    }

    private function writeLlms(): void
    {
        $base = $this->config['base_url'];
        $lines = [
            '# Foundry',
            '',
            "> Foundry is a suite of {$this->classCount()} standalone, single-file PHP utility classes (PHP 8.3+, with PHP 7.4 builds) with zero third-party dependencies. Every failure throws an explicit, descriptive SPL exception instead of returning false or null.",
            '',
            'All classes live in the `Foundry` namespace and are independent of each other: copy only the files you need into a project and load them with require_once, an SPL autoloader or Composer PSR-4. Error messages never contain user data. Every documentation page has a Markdown version (same URL, `.md` instead of `/`).',
            '',
        ];
        foreach ($this->config['guides'] as $group => $slugs) {
            $lines[] = "## {$group}";
            $lines[] = '';
            foreach ($slugs as $slug) {
                $g = $this->guides[$slug];
                $lines[] = "- [{$g['title']}]({$base}/docs/{$slug}.md): {$g['description']}";
            }
            $lines[] = '';
        }
        foreach ($this->lib->categories as $cat) {
            $lines[] = "## {$cat['name']}";
            $lines[] = '';
            foreach ($cat['classes'] as $n) {
                $c = $this->lib->classes[$n];
                $lines[] = "- [{$c['name']}]({$base}/docs/{$c['slug']}.md): ".Support::plain($c['overview']);
            }
            $lines[] = '';
        }
        $lines[] = '## Optional';
        $lines[] = '';
        $lines[] = "- [Complete documentation in a single file]({$base}/llms-full.txt): every guide and class reference concatenated.";
        Support::write($this->outDir().'/llms.txt', implode("\n", $lines)."\n");

        $full = "# Foundry — complete documentation\n\nSource: {$base}/\n\n";
        foreach ($this->markdownDocs as $doc) {
            $full .= "\n---\n\n".$doc['md'];
        }
        Support::write($this->outDir().'/llms-full.txt', $full);
    }

