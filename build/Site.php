<?php

declare(strict_types=1);

namespace FoundrySite;

use RuntimeException;
use Throwable;
use ZipArchive;

/**
 * Orchestrates the build: reads the library, renders every page, and writes the SEO / AI files.
 */
final class Site
{
    public Library $lib;

    public Linker $linker;

    public Renderer $renderer;

    /** @var list<array{title: string, items: list<array{title: string, url: string}>}> */
    public array $nav = [];

    /** @var array<string, array<string, mixed>> slug => guide */
    public array $guides = [];

    /** @var array{name: string, url: string, size: int, sha256: string, count: int} */
    public array $download;

    public string $buildYear;

    /** @var array<string, string> asset path => version hash */
    private array $assetVersions = [];

    /** @var list<array{loc: string, lastmod: string}> */
    private array $sitemap = [];

    /** @var list<array<string, string>> */
    private array $search = [];

    /** @var list<array{title: string, url: string, md: string}> */
    private array $markdownDocs = [];

    private int $pages = 0;

    /** @param  array<string, mixed>  $config */
    public function __construct(public array $config) {}

    /** @param  list<string>  $argv */
    public static function main(array $argv): int
    {
        $config = require __DIR__.'/config.php';
        foreach (array_slice($argv, 1) as $arg) {
            if (preg_match('/^--base-url=(.+)$/', $arg, $m)) {
                $config['base_url'] = rtrim($m[1], '/');
            } elseif (preg_match('/^--out=(.+)$/', $arg, $m)) {
                $config['output_dir'] = $m[1];
            } else {
                fwrite(STDERR, "Unknown option {$arg}\nUsage: php build.php [--base-url=https://example.com] [--out=path/to/public]\n");

                return 2;
            }
        }

        try {
            (new self($config))->build();
        } catch (Throwable $e) {
            fwrite(STDERR, 'Build failed: '.$e->getMessage().' ('.basename($e->getFile()).':'.$e->getLine().")\n");

            return 1;
        }

        return 0;
    }

    public function build(): void
    {
        $start = microtime(true);
        $this->buildYear = date('Y');

        $this->lib = new Library($this->config);
        $this->lib->load();
        $this->linker = new Linker;
        foreach ($this->lib->classes as $c) {
            $names = array_merge(array_column($c['methods'], 'name'), array_column($c['functions'], 'name'));
            $this->linker->addClass($c['name'], $this->classPath($c), $names);
        }
        $this->renderer = new Renderer($this->linker);

        $out = $this->outDir();
        if (basename($out) !== 'public' && ! is_file($out.'/.foundry-site')) {
            throw new RuntimeException("Refusing to clean {$out}: the output directory must be named 'public'.");
        }
        Support::removeDir($out);
        Support::write($out.'/.foundry-site', "Generated by foundry-library/build.php. Safe to delete.\n");

        $this->copyAssets();
        $this->buildDownload();
        $this->loadGuides();
        $this->buildNav();

        $this->pageHome();
        $this->pageDocsIndex();
        foreach ($this->guides as $guide) {
            $this->pageGuide($guide);
        }
        foreach ($this->lib->classes as $class) {
            $this->pageClass($class);
        }
        $this->page404();

        $this->writeSearchIndex();
        $this->writeSitemap();
        $this->writeRobots();
        $this->writeLlms();
        $this->writeManifest();

        $this->report($start);
    }

    // ------------------------------------------------------------------ helpers used by templates

    public function url(string $path = '/'): string
    {
        return $this->config['base_url'].$path;
    }

    public function asset(string $path): string
    {
        return '/assets/'.$path.(isset($this->assetVersions[$path]) ? '?v='.$this->assetVersions[$path] : '');
    }

    /** @param  array<string, mixed>  $class */
    public function classPath(array $class): string
    {
        return '/docs/'.$class['slug'].'/';
    }

    public function classCount(): int
    {
        return count($this->lib->classes);
    }

    /** Short title fragment from a README overview: first clause, trimmed to fit. */
    public function tagline(array $class, int $max = 56): string
    {
        $plain = Support::plain($class['overview']);
        $first = preg_split('/;\s|\.\s|:\s/', $plain)[0] ?? $plain;

        return Support::excerpt(rtrim($first, '.'), $max);
    }

    /** Hand-written short phrase for a class (content/titles.php), or a tagline from the README. */
    public function phrase(array $class): string
    {
        static $titles = null;
        $titles ??= is_file($this->config['content_dir'].'/titles.php') ? require $this->config['content_dir'].'/titles.php' : [];

        return $titles[$class['name']] ?? $this->tagline($class, 60);
    }

    /** <title> for a class page, at most ~60 characters, cut on a phrase boundary (no ellipsis). */
    public function classTitle(array $class): string
    {
        $suffix = ' | Foundry PHP';
        if ($this->phrase($class) !== $this->tagline($class, 60)) {
            return $class['name'].' — '.$this->phrase($class).$suffix;
        }
        $max = 62 - mb_strlen($class['name']) - 3 - mb_strlen($suffix);
        $text = rtrim(preg_split('/;\s|\.\s|:\s/', Support::plain($class['overview']))[0], '.');
        if (mb_strlen($text) > $max) {
            $cut = mb_substr($text, 0, $max + 1);
            $pos = max((int) mb_strrpos($cut, ', '), (int) mb_strrpos($cut, ' ('), (int) mb_strrpos($cut, ' with '), (int) mb_strrpos($cut, ' and '));
            $text = $pos > $max * 0.45 ? mb_substr($cut, 0, $pos) : mb_substr($cut, 0, (int) mb_strrpos($cut, ' '));
            $text = (string) preg_replace('/\s+(and|or|with|for|of|to|the|a|an|via|against|on|in)$/i', '', rtrim($text, ' ,;(/'));
        }

        return $class['name'].' — '.$text.$suffix;
    }

    /** @param  array<string, mixed>  $vars */
    public function render(string $template, array $vars = []): string
    {
        $file = $this->config['templates_dir'].'/'.$template.'.php';
        if (! is_file($file)) {
            throw new RuntimeException("Template not found: {$template}");
        }
        $site = $this;
        extract($vars, EXTR_SKIP);
        ob_start();
        try {
            include $file;
        } catch (Throwable $e) {
            ob_end_clean();
            throw $e;
        }

        return (string) ob_get_clean();
    }

    public static function jsonLd(array $data): string
    {
        return '<script type="application/ld+json">'
            .json_encode($data, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_HEX_TAG | JSON_THROW_ON_ERROR)
            .'</script>';
    }

