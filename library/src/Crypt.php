<?php

declare(strict_types=1);

namespace Foundry;

use InvalidArgumentException;
use LogicException;
use RuntimeException;
use UnexpectedValueException;

/**
 * Crypt Class
 *
 * Authenticated encryption using AES-256-GCM (openssl) and HMAC-SHA256.
 *
 * GCM detects any modification to the ciphertext: altered text, an incorrect key, or
 * a mismatched context throws an exception during decryption rather than returning corrupted data.
 *
 * Key:
 *   - 32 random bytes, stored as base64 (e.g. in .env: APP_KEY=base64:...);
 *   - generated once using Crypt::generateKey();
 *   - NO default key: a missing or short key throws an exception.
 *
 * Context (optional) binds ciphertext to its intended purpose: an IBAN encrypted with context 'iban'
 * cannot be decrypted with context 'cnp' (e.g. if moved to another column).
 *
 * Key rotation: decrypt() accepts a list of keys (newest key first, followed by previous keys).
 *
 * Format: base64url( version(1) | iv(12) | tag(16) | ciphertext ).
 *
 * Usage:
 *   require_once 'Crypt.php';
 *   use Foundry\Crypt;
 *
 *   $key = Crypt::generateKey();                         // generated once; saved in .env
 *
 *   $stored = Crypt::encrypt($iban, Env::string('APP_KEY'), context: 'client.iban');
 *   $iban = Crypt::decrypt($stored, Env::string('APP_KEY'), context: 'client.iban');
 *
 *   $iban = Crypt::decrypt($stored, [Env::string('APP_KEY'), Env::string('APP_KEY_OLD')], 'client.iban');
 *
 *   $signature = Crypt::hmac($payload, $secret);
 *   if (! Crypt::verifyHmac($payload, $receivedSignature, $secret)) { ... }
 *
 * @category Utilities
 *
 * @version  1.1
 *
 * @since    PHP 8.3
 *
 * @author   Voica Liviu
 * @license  Proprietary
 */
final class Crypt
{
    /** @var string Encryption cipher algorithm. */
    private const string CIPHER = 'aes-256-gcm';

    /** @var string Format version (first byte). */
    private const string VERSION = "\x01";

    /** @var int Key length in bytes. */
    private const int KEY_LENGTH = 32;

    private const int IV_LENGTH = 12;

    private const int TAG_LENGTH = 16;

    private function __construct() {}

    /**
     * Generates a new key formatted as "base64:...". Keep this secret (e.g. in .env).
     */
    public static function generateKey(): string
    {
        return 'base64:'.base64_encode(random_bytes(self::KEY_LENGTH));
    }

    /**
     * Encrypts plaintext.
     *
     * @param  string  $plaintext  Data to encrypt (binary-safe).
     * @param  string  $key  Key as base64 string (with or without "base64:" prefix).
     * @param  string  $context  Purpose of data (optional); must match identically during decryption.
     * @return string Safe for URLs, JSON, and databases (base64url).
     *
     * @throws InvalidArgumentException If the key is invalid.
     * @throws RuntimeException If encryption fails.
     */
    public static function encrypt(string $plaintext, string $key, string $context = ''): string
    {
        self::assertAvailable();
        $rawKey = self::decodeKey($key);

        $iv = random_bytes(self::IV_LENGTH);
        $tag = '';
        $ciphertext = openssl_encrypt($plaintext, self::CIPHER, $rawKey, OPENSSL_RAW_DATA, $iv, $tag, self::VERSION.$context, self::TAG_LENGTH);

        if ($ciphertext === false || strlen($tag) !== self::TAG_LENGTH) {
            throw new RuntimeException('Crypt::encrypt(): encryption failed: '.self::opensslErrors().'.');
        }

        return rtrim(strtr(base64_encode(self::VERSION.$iv.$tag.$ciphertext), '+/', '-_'), '=');
    }

    /**
     * Decrypts a payload generated by encrypt().
     *
     * @param  string  $payload  Encrypted payload string.
     * @param  string|list<string>  $keys  Key or list of keys tried in order (key rotation).
     * @param  string  $context  Same context as used during encryption.
     *
     * @throws InvalidArgumentException If a key is invalid.
     * @throws UnexpectedValueException If data is tampered with, or key/context does not match.
     */
    public static function decrypt(string $payload, string|array $keys, string $context = ''): string
    {
        self::assertAvailable();

        $keys = is_string($keys) ? [$keys] : $keys;
        if ($keys === []) {
            throw new InvalidArgumentException('Crypt::decrypt(): at least one key is required.');
        }
        $rawKeys = array_map(self::decodeKey(...), $keys);

        $data = base64_decode(strtr($payload, '-_', '+/'), true);
        $minimum = 1 + self::IV_LENGTH + self::TAG_LENGTH;

        // Canonical base64url only (unused trailing bits must be zero): one spelling per payload.
        if ($data === false || rtrim(strtr(base64_encode($data), '+/', '-_'), '=') !== rtrim($payload, '=')
            || strlen($data) < $minimum || $data[0] !== self::VERSION) {
            throw new UnexpectedValueException('Crypt::decrypt(): the payload is not valid encrypted data.');
        }

        $iv = substr($data, 1, self::IV_LENGTH);
        $tag = substr($data, 1 + self::IV_LENGTH, self::TAG_LENGTH);
        $ciphertext = substr($data, $minimum);

        foreach ($rawKeys as $rawKey) {
            $plaintext = openssl_decrypt($ciphertext, self::CIPHER, $rawKey, OPENSSL_RAW_DATA, $iv, $tag, self::VERSION.$context);
            if ($plaintext !== false) {
                return $plaintext;
            }
        }

        self::opensslErrors(); // goleste coada de erori openssl

        // Nu se precizeaza care conditie a esuat: un atacator nu trebuie sa afle daca a ghicit ceva.
        throw new UnexpectedValueException('Crypt::decrypt(): decryption failed (wrong key or context, or the data was modified).');
    }

    /**
     * Generates HMAC-SHA256 as lowercase hexadecimal string (64 characters). For signing webhooks, URLs, etc.
     *
     * @throws InvalidArgumentException If the secret has fewer than 32 bytes.
     */
    public static function hmac(string $data, string $secret): string
    {
        self::assertSecret('hmac', $secret);

        return hash_hmac('sha256', $data, $secret);
    }

    /**
     * Verifies an HMAC-SHA256 in constant time (preventing timing attacks).
     *
     * @throws InvalidArgumentException If the secret has fewer than 32 bytes.
     */
    public static function verifyHmac(string $data, string $mac, string $secret): bool
    {
        self::assertSecret('verifyHmac', $secret);

        return hash_equals(hash_hmac('sha256', $data, $secret), strtolower($mac));
    }

    /**
     * Extracts raw 32-byte key from base64 string.
     *
     * @throws InvalidArgumentException If the key is not valid base64 of 32 bytes.
     */
    private static function decodeKey(string $key): string
    {
        $encoded = str_starts_with($key, 'base64:') ? substr($key, 7) : $key;
        $raw = base64_decode($encoded, true);

        if ($raw === false || strlen($raw) !== self::KEY_LENGTH) {
            throw new InvalidArgumentException('Crypt: the key must be '.self::KEY_LENGTH.' random bytes encoded as base64 (use Crypt::generateKey()).');
        }

        return $raw;
    }

    /**
     * @throws InvalidArgumentException If the secret is too short.
     */
    private static function assertSecret(string $method, string $secret): void
    {
        if (strlen($secret) < self::KEY_LENGTH) {
            throw new InvalidArgumentException("Crypt::{$method}(): the secret must be at least ".self::KEY_LENGTH.' bytes long.');
        }
    }

    /**
     * @throws LogicException If the openssl extension is missing.
     */
    private static function assertAvailable(): void
    {
        if (! function_exists('openssl_encrypt') || ! in_array(self::CIPHER, openssl_get_cipher_methods(), true)) {
            throw new LogicException('Crypt: the PHP openssl extension (with '.self::CIPHER.') is not enabled.');
        }
    }

    /**
     * Retrieves error messages from the openssl error queue (and clears it).
     */
    private static function opensslErrors(): string
    {
        $errors = [];
        while (($error = openssl_error_string()) !== false) {
            $errors[] = $error;
        }

        return $errors === [] ? 'unknown error' : implode('; ', $errors);
    }
}
